    #[test]
    fn installer_and_uninstaller_report_every_launcher_file_left_alone() {
        let foreign_cmd = "@echo off\r\nC:\\other\\omo.exe %*\r\n";

        for (omo_owned, cmd_owned, expected_files) in [
            (true, false, vec!["omo.cmd"]),
            (false, true, vec!["omo"]),
            (false, false, vec!["omo", "omo.cmd"]),
            (true, true, vec![]),
        ] {
            let temp = tempfile::tempdir().expect("temp");
            let home = temp.path().join("home");
            let agent = temp.path().join("agent");
            let plugin = temp.path().join("plugin");
            let settings = agent.join("settings.json");
            for artifact in REQUIRED_PLUGIN_ARTIFACTS {
                let path = plugin.join(artifact);
                fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
                fs::write(path, b"artifact").expect("write");
            }
            scratch_bin_dir(&home);
            if omo_owned {
                install_local_launcher(&home, &plugin, Path::new("/cli.js"), None, "linux")
                    .expect("install omo");
            } else {
                fs::write(local_launcher_path(&home), compiled_binary_bytes()).expect("bin");
            }
            fs::write(
                local_launcher_cmd_path(&home),
                if cmd_owned {
                    LAUNCHER_CMD_SHIM
                } else {
                    foreign_cmd
                },
            )
            .expect("cmd");

            let result = run_plugin_installer(&PluginInstallerOptions {
                settings_path: &settings,
                plugin_path: &plugin,
                repo_root: temp.path(),
                agent_dir: &agent,
                home_dir: &home,
                cli_path: Path::new("/cli.js"),
                version: None,
                platform: "win32",
            })
            .expect("run installer");

            let actual_files: Vec<&str> = result
                .launchers_left_alone
                .iter()
                .map(|entry| entry.file)
                .collect();
            assert_eq!(actual_files, expected_files);
            for entry in &result.launchers_left_alone {
                let expected_path = if entry.file == "omo" {
                    local_launcher_path(&home)
                } else {
                    local_launcher_cmd_path(&home)
                };
                assert_eq!(entry.path, expected_path);
            }
            assert_eq!(
                result.launcher_path,
                if omo_owned {
                    Some(local_launcher_path(&home))
                } else {
                    None
                }
            );
        }

        let uninstall_temp = tempfile::tempdir().expect("temp");
        let home = uninstall_temp.path().join("home");
        let agent = uninstall_temp.path().join("agent");
        let plugin = uninstall_temp.path().join("plugin");
        let settings = agent.join("settings.json");
        scratch_bin_dir(&home);
        fs::write(local_launcher_path(&home), compiled_binary_bytes()).expect("bin");
        let uninst = run_plugin_uninstaller(&PluginInstallerOptions {
            settings_path: &settings,
            plugin_path: &plugin,
            repo_root: uninstall_temp.path(),
            agent_dir: &agent,
            home_dir: &home,
            cli_path: Path::new("/cli.js"),
            version: None,
            platform: "linux",
        })
        .expect("run uninstaller");
        assert!(local_launcher_path(&home).exists());
        assert_eq!(
            uninst
                .launchers_left_alone
                .iter()
                .map(|entry| (entry.file, entry.path.clone()))
                .collect::<Vec<_>>(),
            vec![("omo", local_launcher_path(&home))]
        );
    }
