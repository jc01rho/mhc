#[derive(Debug, Error)]
pub enum PluginArtifactError {
    #[error("Packed maho plugin is missing required runtime artifact: {0}")]
    MissingArtifact(PathBuf),
    #[error("Plugin artifact could not be inspected at {path}: {source}")]
    Inspect {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("Plugin ast-grep MCP runtime integrity error at {path}: {reason}")]
    AstGrepIntegrity { path: PathBuf, reason: String },
}

